//! Raw FFI bindings to the cuGraph C API.
//!
//! Published as an Algeon implementation dependency. Applications use
//! [`algeon-datafusion`](https://docs.rs/algeon-datafusion); workspace code
//! uses this crate for its component contracts. See the
//! [API documentation boundary](https://algeon.dev/design#api-documentation).
//!
//! This crate provides checked-in bindings generated with `bindgen`. Safe
//! APIs are exposed by the [`cugraph`](https://docs.rs/algeon-cugraph) crate.

#![allow(non_upper_case_globals)]
#![allow(non_camel_case_types)]
#![allow(clippy::all)]
#![allow(clippy::allow_attributes)]
// reason = "generated by bindgen"
// The bindings carry cuGraph's C (Doxygen) doc comments verbatim. Constructs like
// `@param [in]` and bare URLs are not valid rustdoc, so silence the doc lints that
// would otherwise fire on every generated item.
#![allow(rustdoc::broken_intra_doc_links)]
#![allow(rustdoc::bare_urls)]

include!("bindings.rs");
