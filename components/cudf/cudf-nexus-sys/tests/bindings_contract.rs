//! Source-level conformance checks for the checked-in bindgen output.

use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
};

const CARGO_TOML: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/Cargo.toml"));
const CARGO_LOCK: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../Cargo.lock"));
const GENERATOR: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/bindings/generate.sh"));
const WRAPPER: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/bindings/wrapper.h"));
const PRODUCTION_BINDINGS: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/bindings.rs"));
const TEST_BINDINGS: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/test_support.rs"));
const LIB_RS: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/lib.rs"));
const COLUMN_HEADER: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/native/include/cudf_rust/column.h"));
const MEMORY_HEADER: &str =
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/native/include/cudf_rust/memory_resource.h"));
const STRINGS_HEADER: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/native/include/cudf_rust/strings.h"));

const PRODUCTION_PREFIX: &str = "// Generated by bindgen-cli 0.72.1 with the following exact command:\n";
const TEST_PREFIX: &str = "// Generated by bindgen-cli 0.72.1 with the following exact command:\n";
const DO_NOT_EDIT: &str = "// DO NOT EDIT. Run ./cudf-nexus-sys/bindings/generate.sh to regenerate.";

fn without_c_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let bytes = source.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index..].starts_with(b"//") {
            index += 2;
            while index < bytes.len() && bytes[index] != b'\n' {
                index += 1;
            }
        } else if bytes[index..].starts_with(b"/*") {
            index += 2;
            while index + 1 < bytes.len() && !bytes[index..].starts_with(b"*/") {
                index += 1;
            }
            index = (index + 2).min(bytes.len());
        } else {
            out.push(bytes[index] as char);
            index += 1;
        }
    }
    out
}

fn names_followed_by_open_paren(source: &str, marker: &str) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    let mut remaining = source;
    while let Some(offset) = remaining.find(marker) {
        let suffix = &remaining[offset + marker.len()..];
        let name_len = suffix.bytes().take_while(|byte| byte.is_ascii_alphanumeric() || *byte == b'_').count();
        let (name, after_name) = suffix.split_at(name_len);
        if !name.is_empty() && after_name.trim_start().starts_with('(') {
            names.insert(format!("{marker}{name}"));
        }
        remaining = &suffix[name_len..];
    }
    names
}

fn c_function_names(source: &str) -> BTreeSet<String> {
    names_followed_by_open_paren(&without_c_comments(source), "cudf_")
}

fn generated_function_names(source: &str) -> BTreeSet<String> {
    names_followed_by_open_paren(source, "pub fn cudf_")
        .into_iter()
        .map(|name| name.strip_prefix("pub fn ").expect("generated function prefix").to_owned())
        .collect()
}

fn public_header_paths() -> Vec<PathBuf> {
    let header_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("native/include/cudf_rust");
    let mut paths = fs::read_dir(header_dir)
        .expect("read public C header directory")
        .map(|entry| entry.expect("read public C header entry").path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "h"))
        .filter(|path| path.file_name().is_none_or(|name| name != "test_support.h"))
        .collect::<Vec<_>>();
    paths.sort();
    paths
}

fn public_c_function_names() -> BTreeSet<String> {
    public_header_paths().into_iter().fold(BTreeSet::new(), |mut names, path| {
        names.extend(c_function_names(&fs::read_to_string(path).expect("read public C header")));
        names
    })
}

#[test]
fn generated_sources_record_the_pinned_reproducible_command() {
    for generated in [PRODUCTION_BINDINGS, TEST_BINDINGS] {
        assert!(generated.starts_with(PRODUCTION_PREFIX));
        assert!(generated.contains("/* automatically generated by rust-bindgen 0.72.1 */"));
        assert!(generated.contains(DO_NOT_EDIT));
    }
    assert!(TEST_BINDINGS.starts_with(TEST_PREFIX));

    assert!(GENERATOR.contains("readonly bindgen_version=\"0.72.1\""));
    assert!(GENERATOR.contains("--default-enum-style consts"));
    assert!(GENERATOR.contains("--check"));
    assert!(GENERATOR.contains("cmp -s \"${temporary}\" \"${output}\""));
    assert!(GENERATOR.contains("chmod 0644 \"${temporary}\""));
    assert!(GENERATOR.contains("generate src/bindings.rs production"));
    assert!(GENERATOR.contains("generate src/test_support.rs test-support"));
}

#[test]
fn handwritten_ffi_sources_and_bindgen_build_dependencies_are_absent() {
    let source_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    assert!(!source_root.join("ffi").exists());
    assert!(!source_root.join("types.rs").exists());
    assert!(!LIB_RS.contains("mod ffi;"));
    assert!(!LIB_RS.contains("mod types;"));

    for entry in fs::read_dir(&source_root).expect("read sys source directory") {
        let entry = entry.expect("read sys source entry");
        let path = entry.path();
        if path.extension().is_some_and(|extension| extension == "rs")
            && !matches!(path.file_name().and_then(|name| name.to_str()), Some("bindings.rs" | "test_support.rs"))
        {
            let source = fs::read_to_string(&path).expect("read handwritten sys source");
            assert!(
                !source.contains("unsafe extern \"C\" {"),
                "handwritten production FFI declaration remains in {}",
                path.display()
            );
        }
    }

    assert!(!CARGO_TOML.contains("bindgen ="), "bindgen must not be a sys-crate build or development dependency");
    assert!(!CARGO_LOCK.contains("name = \"bindgen\""), "consumer lockfile must not gain the bindgen library");
}

