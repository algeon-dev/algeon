#[test]
fn memory_manager_partition_limit_has_one_synchronized_abi_layout() {
    #[repr(C)]
    struct OriginalOptionsLayout {
        struct_size: usize,
        base_kind: cudf_sys::cudf_memory_manager_base_kind_t,
        flags: u32,
        initial_pool_size_bytes: u64,
        maximum_pool_size_bytes: u64,
        release_threshold_bytes: u64,
        reserved: [u64; 4],
    }

    let defaults = cudf_sys::cudf_memory_manager_options_t::default();
    assert_eq!(defaults.allocation_limit_bytes, 0);
    assert_eq!(defaults.reserved.len(), cudf_sys::CUDF_MEMORY_MANAGER_OPTIONS_RESERVED_SLOTS as usize);
    assert_eq!(std::mem::offset_of!(cudf_sys::cudf_memory_manager_options_t, allocation_limit_bytes), 40);
    assert_eq!(std::mem::size_of::<cudf_sys::cudf_memory_manager_options_t>(), 72);
    assert_eq!(std::mem::size_of::<OriginalOptionsLayout>(), 72);
    assert_eq!(std::mem::offset_of!(OriginalOptionsLayout, reserved), 40);
    let original = OriginalOptionsLayout {
        struct_size: std::mem::size_of::<OriginalOptionsLayout>(),
        base_kind: cudf_sys::CUDF_MEMORY_MANAGER_BASE_CUDA_ASYNC,
        flags: 0,
        initial_pool_size_bytes: 0,
        maximum_pool_size_bytes: 0,
        release_threshold_bytes: u64::MAX,
        reserved: [0; 4],
    };
    let compatible = unsafe {
        std::ptr::read_unaligned(std::ptr::from_ref(&original).cast::<cudf_sys::cudf_memory_manager_options_t>())
    };
    assert_eq!(compatible.allocation_limit_bytes, 0, "a zeroed old reserved slot remains unbounded");
    assert!(MEMORY_MANAGER_HEADER.contains("uint64_t allocation_limit_bytes;"));
    assert!(PRODUCTION_BINDINGS.contains("pub allocation_limit_bytes: u64,"));
}
