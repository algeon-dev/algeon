#[test]
fn production_bindings_exclude_test_support_and_foreign_rust_enums() {
    assert!(WRAPPER.contains("#include <cudf_rust/cudf_rust.h>"));
    assert!(WRAPPER.contains("#ifdef CUDF_RUST_BINDINGS_TEST_SUPPORT"));
    assert!(WRAPPER.contains("#include <cudf_rust/test_support.h>"));

    assert!(!PRODUCTION_BINDINGS.contains("cudf_test_"));
    assert!(!PRODUCTION_BINDINGS.contains("CUDF_TEST_"));
    assert!(
        !PRODUCTION_BINDINGS.contains("pub enum "),
        "foreign C enum values must remain raw integer aliases/constants"
    );
    assert!(PRODUCTION_BINDINGS.contains("pub type cudf_status_t = core::ffi::c_uint;"));
    assert!(PRODUCTION_BINDINGS.contains("pub type cudf_type_id_t = core::ffi::c_uint;"));
}

#[test]
fn test_support_generated_surface_is_namespaced_to_test_symbols() {
    assert!(TEST_BINDINGS.contains("use crate::*;"));
    assert!(!TEST_BINDINGS.contains("pub enum "));
    for production_alias in [
        "pub type cudf_status_t",
        "pub type cudf_stream_handle",
        "pub type cudf_memory_resource_handle",
        "pub type cudf_memory_manager_handle",
        "pub type cudf_column_view_handle",
        "pub type cudf_type_id_t",
        "pub type cudf_arrow_device_array_handle",
    ] {
        assert!(
            !TEST_BINDINGS.contains(production_alias),
            "test-support output must import, rather than redefine, production ABI alias `{production_alias}`"
        );
    }

    for line in TEST_BINDINGS.lines().map(str::trim) {
        if line.starts_with("pub type ") {
            assert!(line.starts_with("pub type cudf_test_"), "unexpected generated test-support type: {line}");
        }
        if line.starts_with("pub const ") {
            assert!(line.starts_with("pub const CUDF_TEST_"), "unexpected generated test-support constant: {line}");
        }
        if line.starts_with("pub fn ") {
            assert!(line.starts_with("pub fn cudf_test_"), "unexpected generated test-support function: {line}");
        }
    }
}

#[test]
fn generated_function_names_exactly_match_their_c_header_boundaries() {
    let production_c_names = public_c_function_names();
    let test_c_names = c_function_names(
        &fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("native/include/cudf_rust/test_support.h"))
            .expect("read test-support C header"),
    );

    let production_rust_names = generated_function_names(PRODUCTION_BINDINGS);
    let test_rust_names = generated_function_names(TEST_BINDINGS);

    assert_eq!(production_rust_names, production_c_names);
    assert_eq!(test_rust_names, test_c_names);
    assert!(production_rust_names.is_disjoint(&test_c_names));
}

#[test]
fn representative_c_declarations_have_generated_raw_counterparts() {
    assert!(COLUMN_HEADER.contains("cudf_status_t cudf_column_view_data_type(cudf_column_view_handle handle,"));
    assert!(PRODUCTION_BINDINGS.contains("pub fn cudf_column_view_data_type("));
    assert!(PRODUCTION_BINDINGS.contains("out_type_id: *mut cudf_type_id_t,"));

    assert!(MEMORY_HEADER.contains("cudf_memory_resource_create_cuda("));
    let compact_memory_header = MEMORY_HEADER.split_ascii_whitespace().collect::<String>();
    assert!(compact_memory_header.contains("cudf_memory_resource_handle*out"));
    assert!(
        PRODUCTION_BINDINGS.contains("pub fn cudf_memory_resource_create_cuda(out: *mut cudf_memory_resource_handle)")
    );

    assert!(STRINGS_HEADER.contains("cudf_status_t cudf_strings_execute_replace_with_backrefs_ex("));
    assert!(PRODUCTION_BINDINGS.contains("pub fn cudf_strings_execute_replace_with_backrefs_ex("));
    assert!(PRODUCTION_BINDINGS.contains("handle: cudf_prepared_replace_with_backrefs_handle,"));
}
