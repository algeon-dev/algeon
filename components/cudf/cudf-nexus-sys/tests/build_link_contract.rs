#[test]
fn collect_native_clang_lint_files_is_scoped_to_src_and_include() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let lint_files = build_support::lint::collect_native_clang_lint_files(manifest_dir).unwrap();

    assert!(!lint_files.is_empty(), "expected cudf-nexus-sys/native to expose at least one clang-lintable file");
    assert!(
        lint_files.iter().all(|path| path.starts_with(manifest_dir.join("native/src"))
            || path.starts_with(manifest_dir.join("native/include"))),
        "expected clang lint files to stay within cudf-nexus-sys/native/src and cudf-nexus-sys/native/include: {lint_files:?}"
    );
    assert!(
        lint_files.iter().all(|path| build_support::lint::is_clang_lintable_path(path)),
        "expected every collected file to satisfy the lintable-path predicate: {lint_files:?}"
    );
    let upstream_native = manifest_dir.join("../cudf");
    assert!(
        lint_files.iter().all(|path| !path.starts_with(&upstream_native)),
        "expected upstream cudf files to stay out of cudf-nexus-sys lint scope: {lint_files:?}"
    );

    // The collector appends `native/src` and `native/include` to the crate
    // manifest directory itself, so handing it the native directory
    // double-prefixes the lookup and must be rejected.
    let error = build_support::lint::collect_native_clang_lint_files(&build_support::lint::native_dir(manifest_dir))
        .unwrap_err();
    assert!(
        error.contains("failed to read clang lint directory"),
        "expected the native directory to be rejected as a lint root: {error}"
    );
}

