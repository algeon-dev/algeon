#!/usr/bin/env bash
# Regenerate the checked-in raw C ABI bindings. Consumer builds never run this.
set -euo pipefail

readonly bindgen_version="0.72.1"
readonly repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
readonly bindgen_bin="${BINDGEN:-bindgen}"
readonly wrapper="components/cudf/cudf-nexus-sys/bindings/wrapper.h"
readonly include_dir="components/cudf/cudf-nexus-sys/native/include"
readonly production_output="components/cudf/cudf-nexus-sys/src/bindings.rs"
readonly test_output="components/cudf/cudf-nexus-sys/src/test_support.rs"

usage() {
  printf 'usage: %s [--check]\n' "${0##*/}" >&2
}

check=0
case "${1:-}" in
  '') ;;
  --check) check=1 ;;
  *)
    usage
    exit 2
    ;;
esac

if ! installed_version="$(${bindgen_bin} --version)"; then
  printf 'error: bindgen-cli %s is required; install with: cargo install --locked bindgen-cli --version %s\n' \
    "${bindgen_version}" "${bindgen_version}" >&2
  exit 1
fi

if [[ "${installed_version}" != "bindgen ${bindgen_version}" ]]; then
  printf 'error: expected bindgen %s, found %s\n' "${bindgen_version}" "${installed_version}" >&2
  exit 1
fi

if [[ -z "${RUSTFMT:-}" ]]; then
  export RUSTFMT="$(rustup which rustfmt --toolchain nightly)"
fi

cd "${repo_root}"

generate() {
  local output="$1"
  local kind="$2"
  local temporary
  temporary="$(mktemp "${output}.tmp.XXXXXX")"

  if ! {
    printf '%s\n' '// Generated by bindgen-cli 0.72.1 with the following exact command:'
    if [[ "${kind}" == production ]]; then
      printf '%s\n' '// bindgen components/cudf/cudf-nexus-sys/bindings/wrapper.h --allowlist-function ^cudf_.* --allowlist-type ^cudf_.* --allowlist-var ^CUDF_.* --default-enum-style consts --no-prepend-enum-name --no-layout-tests --use-core --ctypes-prefix core::ffi --rust-target 1.94 --rust-edition 2024 --sort-semantically --merge-extern-blocks --formatter rustfmt -- -I components/cudf/cudf-nexus-sys/native/include -xc'
    else
      printf '%s\n' '// bindgen components/cudf/cudf-nexus-sys/bindings/wrapper.h --allowlist-function ^cudf_test_.* --allowlist-type ^cudf_test_.* --allowlist-var ^CUDF_TEST_.* --blocklist-type ^cudf_(status_t|stream_handle|memory_resource_handle|memory_manager_handle|column_view_handle|type_id_t|arrow_device_array_handle)(_state)?$ --default-enum-style consts --no-prepend-enum-name --no-layout-tests --use-core --ctypes-prefix core::ffi --rust-target 1.94 --rust-edition 2024 --sort-semantically --merge-extern-blocks --formatter rustfmt --raw-line use crate::* -- -DCUDF_RUST_BINDINGS_TEST_SUPPORT -I components/cudf/cudf-nexus-sys/native/include -xc'
    fi
    printf '%s\n' '// DO NOT EDIT. Run ./components/cudf/cudf-nexus-sys/bindings/generate.sh to regenerate.'
    printf '\n'

    if [[ "${kind}" == production ]]; then
      "${bindgen_bin}" "${wrapper}" \
        --allowlist-function '^cudf_.*' \
        --allowlist-type '^cudf_.*' \
        --allowlist-var '^CUDF_.*' \
        --default-enum-style consts \
        --no-prepend-enum-name \
        --no-layout-tests \
        --use-core \
        --ctypes-prefix core::ffi \
        --rust-target 1.94 \
        --rust-edition 2024 \
        --sort-semantically \
        --merge-extern-blocks \
        --formatter rustfmt \
        -- -I "${include_dir}" -xc
    else
      "${bindgen_bin}" "${wrapper}" \
        --allowlist-function '^cudf_test_.*' \
        --allowlist-type '^cudf_test_.*' \
        --allowlist-var '^CUDF_TEST_.*' \
        --blocklist-type '^cudf_(status_t|stream_handle|memory_resource_handle|memory_manager_handle|column_view_handle|type_id_t|arrow_device_array_handle)(_state)?$' \
        --default-enum-style consts \
        --no-prepend-enum-name \
        --no-layout-tests \
        --use-core \
        --ctypes-prefix core::ffi \
        --rust-target 1.94 \
        --rust-edition 2024 \
        --sort-semantically \
        --merge-extern-blocks \
        --formatter rustfmt \
        --raw-line 'use crate::*;' \
        -- -DCUDF_RUST_BINDINGS_TEST_SUPPORT -I "${include_dir}" -xc
    fi
  } >"${temporary}"; then
    rm -f "${temporary}"
    return 1
  fi
  chmod 0644 "${temporary}"

  if ((check)); then
    if ! cmp -s "${temporary}" "${output}"; then
      printf 'error: %s is stale; run ./components/cudf/cudf-nexus-sys/bindings/generate.sh\n' "${output}" >&2
      rm -f "${temporary}"
      return 1
    fi
    rm -f "${temporary}"
  else
    mv "${temporary}" "${output}"
  fi
}

generate "${production_output}" production
generate "${test_output}" test-support
