#[test]
fn manifest_parser_ignores_comments_and_blank_lines() {
    let directives = build_support::parse_cargo_link_directives(
        r#"
        # Generated by CMake.

        cargo:rustc-link-search=native=/tmp/cudf/lib
        cargo:rustc-link-lib=dylib=cudf_rust
        cargo:metadata=cuda-runtime=shared
        "#,
    )
    .unwrap();

    assert_eq!(
        directives,
        vec![
            "cargo:rustc-link-search=native=/tmp/cudf/lib",
            "cargo:rustc-link-lib=dylib=cudf_rust",
            "cargo:metadata=cuda-runtime=shared",
        ]
    );
}

#[test]
fn manifest_parser_rejects_non_cargo_lines() {
    let error = build_support::parse_cargo_link_directives(
        r#"
        cargo:rustc-link-lib=dylib=cudf_rust
        libcudf.so
        "#,
    )
    .unwrap_err();

    assert!(error.contains("line 3"), "unexpected error: {error}");
}

#[test]
fn read_cargo_link_directives_uses_expected_install_location() {
    let unique = SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos();
    let install_prefix = std::env::temp_dir().join(format!("cudf-sys-build-link-contract-{unique}"));
    let manifest_path = build_support::cargo_link_manifest_path(&install_prefix);
    fs::create_dir_all(manifest_path.parent().unwrap()).unwrap();
    fs::write(&manifest_path, "cargo:rustc-link-search=native=/tmp/cudf/lib\ncargo:rustc-link-lib=dylib=cudf_rust\n")
        .unwrap();

    let directives = build_support::read_cargo_link_directives(&install_prefix).unwrap();

    assert_eq!(
        directives,
        vec!["cargo:rustc-link-search=native=/tmp/cudf/lib", "cargo:rustc-link-lib=dylib=cudf_rust",]
    );

    fs::remove_file(&manifest_path).unwrap();
    fs::remove_dir_all(&install_prefix).unwrap();
}

#[test]
fn parse_cmake_bool_normalizes_common_truthy_and_falsey_values() {
    for truthy in ["1", "on", "TRUE", "Yes"] {
        assert_eq!(build_support::parse_cmake_bool("CUDA_STATIC_RUNTIME", truthy).unwrap(), "ON");
    }

    for falsey in ["0", "off", "FALSE", "No"] {
        assert_eq!(build_support::parse_cmake_bool("CUDA_STATIC_RUNTIME", falsey).unwrap(), "OFF");
    }
}

#[test]
fn parse_cmake_bool_rejects_invalid_values() {
    let error = build_support::parse_cmake_bool("CUDA_STATIC_RUNTIME", "maybe").unwrap_err();
    assert!(error.contains("CUDA_STATIC_RUNTIME"), "unexpected error: {error}");
}

#[test]
fn normalized_cmake_bool_from_env_reads_optional_env_input() {
    let _guard = ENV_LOCK.lock().unwrap();
    std::env::remove_var("CUDA_STATIC_RUNTIME");
    assert_eq!(build_support::normalized_cmake_bool_from_env("CUDA_STATIC_RUNTIME").unwrap(), None);

    std::env::set_var("CUDA_STATIC_RUNTIME", "yes");
    assert_eq!(build_support::normalized_cmake_bool_from_env("CUDA_STATIC_RUNTIME").unwrap(), Some("ON"));

    std::env::remove_var("CUDA_STATIC_RUNTIME");
}

