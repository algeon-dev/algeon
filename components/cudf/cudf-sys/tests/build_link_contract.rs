#[test]
fn read_cargo_link_directives_uses_expected_install_location() {
    let unique = SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos();
    let install_prefix = std::env::temp_dir().join(format!("cudf-sys-build-link-contract-{unique}"));
    let manifest_path = build_support::cargo_link_manifest_path(&install_prefix);
    fs::create_dir_all(manifest_path.parent().unwrap()).unwrap();
    fs::write(&manifest_path, "cargo:rustc-link-search=native=/tmp/cudf/lib\ncargo:rustc-link-lib=dylib=cudf_rust\n")
        .unwrap();

    let directives = build_support::read_cargo_link_directives(&install_prefix).unwrap();

    assert_eq!(
        directives,
        vec!["cargo:rustc-link-search=native=/tmp/cudf/lib", "cargo:rustc-link-lib=dylib=cudf_rust",]
    );

    fs::remove_file(&manifest_path).unwrap();
    fs::remove_dir_all(&install_prefix).unwrap();
}

