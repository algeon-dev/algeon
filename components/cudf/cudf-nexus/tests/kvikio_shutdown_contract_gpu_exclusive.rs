use cudf::{
    DataFrame, ErrorCode, ErrorKind, ErrorStatus, Runtime,
    io::{KvikioCompatMode, drain_kvikio_bounce_buffer_pools, kvikio_compat_mode, set_kvikio_compat_mode},
};
use tempfile::TempDir;

struct CompatModeRestore(KvikioCompatMode);

impl Drop for CompatModeRestore {
    fn drop(&mut self) {
        let _ = set_kvikio_compat_mode(self.0);
    }
}

struct ActiveIoGuard {
    active: bool,
}

impl ActiveIoGuard {
    fn begin() -> Self {
        // SAFETY: the dedicated test binary serializes this process-global
        // hook and the guard balances the increment on every exit path.
        let status = unsafe { cudf_sys::test_support::cudf_test_io_kvikio_active_io_begin() };
        assert_eq!(status, cudf_sys::CUDF_SUCCESS);
        Self { active: true }
    }

    fn end(mut self) {
        // SAFETY: this is the matching decrement for `begin` above.
        let status = unsafe { cudf_sys::test_support::cudf_test_io_kvikio_active_io_end() };
        self.active = false;
        assert_eq!(status, cudf_sys::CUDF_SUCCESS);
    }
}

impl Drop for ActiveIoGuard {
    fn drop(&mut self) {
        if self.active {
            // SAFETY: best-effort unwind cleanup for the increment owned by
            // this guard. The normal path asserts the returned status.
            let _ = unsafe { cudf_sys::test_support::cudf_test_io_kvikio_active_io_end() };
        }
    }
}

#[test]
fn compat_parquet_roundtrip_drains_kvikio_bounce_pools() {
    let original_mode = kvikio_compat_mode().expect("test requires a libcudf build with KvikIO remote I/O");
    let _restore_mode = CompatModeRestore(original_mode);
    set_kvikio_compat_mode(KvikioCompatMode::On).expect("enable KvikIO compatibility mode");
    assert_eq!(kvikio_compat_mode(), Some(KvikioCompatMode::On));

    // Start from an idle, drained pool so the final pair tests the lifecycle
    // generated by this real local Parquet round trip alone.
    drain_kvikio_bounce_buffer_pools().expect("initial idle drain");

    let dir = TempDir::new().unwrap();
    let path = dir.path().join("kvikio-shutdown-contract.parquet");
    let runtime = Runtime::builder().with_device_memory_manager().build().unwrap();
    let frame = DataFrame::from_series([
        ("id", runtime.series(&[1_i32, 2, 3, 4]).unwrap()),
        ("value", runtime.series(&[10_i64, 20, 30, 40]).unwrap()),
    ])
    .unwrap();
    frame.write_parquet(&path).expect("compat-mode Parquet write");

    let decoded = DataFrame::read_parquet(&runtime, &path).expect("compat-mode Parquet read");
    assert_eq!(decoded.column_names(), vec!["id", "value"]);
    assert_eq!(decoded.series("id").unwrap().to_vec_strict::<i32>().unwrap(), vec![1, 2, 3, 4]);
    assert_eq!(decoded.series("value").unwrap().to_vec_strict::<i64>().unwrap(), vec![10, 20, 30, 40]);
    drop(decoded);
    drop(frame);
    drop(runtime);

    let active_io = ActiveIoGuard::begin();
    let error = drain_kvikio_bounce_buffer_pools().expect_err("active I/O must fence pool destruction");
    assert_eq!(error.code(), ErrorCode::IoBusy);
    assert_eq!(error.kind(), ErrorKind::ResourceExhausted);
    assert_eq!(error.status(), ErrorStatus::Temporary);
    assert_eq!(error.detail_value("reason"), Some("active_io"));
    active_io.end();

    drain_kvikio_bounce_buffer_pools().expect("first idle drain after real I/O");
    assert_eq!(
        drain_kvikio_bounce_buffer_pools().expect("second idle drain"),
        0,
        "draining an already empty KvikIO pool must be idempotent"
    );
}
