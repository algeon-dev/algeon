#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
bindings="${repo_root}/cuvs-nexus-sys/src/bindings.rs"

if rg -n 'doc-only|generate-bindings|cfg!\(feature|cfg\(feature' \
    "${repo_root}/cuvs-nexus-sys/Cargo.toml" "${repo_root}/cuvs-nexus-sys/build.rs"; then
    echo "error: maintenance-only build modes must not be exposed as additive sys-crate features" >&2
    exit 1
fi
for required in 'DOCS_RS' 'CUVS_NEXUS_SYS_SKIP_NATIVE' 'workspace_root.join("cuvs-install")'; do
    rg -Fq "${required}" "${repo_root}/cuvs-nexus-sys/build.rs" || {
        echo "error: native-free documentation/lint mode is missing ${required}" >&2
        exit 1
    }
done
rg -Fq 'cuvs-nexus-bindings-generator' "${repo_root}/scripts/generate-bindings.sh" || {
    echo "error: checked-in bindings must be generated by the dedicated workspace tool" >&2
    exit 1
}

for required in \
    'pub struct cuvsKMeansParams_v2' \
    'Size of cuvsKMeansParams_v2.*72usize' \
    'cuvsKMeansParams_v2::hierarchical\"][^;]*48usize' \
    'cuvsKMeansParams_v2::init_size\"][^;]*64usize' \
    'pub fn cuvsKMeansParamsCreate_v2' \
    'pub fn cuvsKMeansParamsDestroy_v2' \
    'pub fn cuvsKMeansFit_v2' \
    'pub fn cuvsKMeansPredict_v2' \
    'pub fn cuvsVersionGet'; do
    rg -Uq "${required}" "${bindings}" || {
        echo "error: generated binding contract is missing pattern: ${required}" >&2
        exit 1
    }
done

rg -q 'reject_private_dependency_path' "${repo_root}/cuvs-nexus-sys/cmake.rs" || {
    echo "error: CMake discovery does not reject private _deps paths" >&2
    exit 1
}
if rg -n 'workspace_parent|default_link_dirs|CUGRAPH_CMAKE_BUILD_DIR' \
    "${repo_root}/cuvs-nexus-sys" "${repo_root}/scripts" --glob '!check_bindings_contract.sh'; then
    echo "error: cuVS build/discovery contains an ambient sibling/fallback path resolver" >&2
    exit 1
fi

for required in \
    'CUDAToolkit_ROOT' \
    'CUDA_HOME' \
    'CUDA_PATH' \
    'cuda_runtime.h' \
    'libcudart.so' \
    'cuda.lib_dir' \
    'DLPACK_INCLUDE_DIR' \
    'dlpack/dlpack.h' \
    'compile_abi_probe(&include_dirs)'; do
    rg -Fq "${required}" "${repo_root}/cuvs-nexus-sys/build.rs" || {
        echo "error: ABI probe CUDA include discovery is missing contract: ${required}" >&2
        exit 1
    }
done

rg -Fq 'share/cuvs-nexus/rmm-runtime-lib' "${repo_root}/cuvs-nexus-sys/cmake.rs" || {
    echo "error: CMake discovery does not require the canonical RMM runtime identity marker" >&2
    exit 1
}
rg -Fq 'patchelf --set-rpath' "${repo_root}/scripts/build_libcuvs.sh" || {
    echo "error: canonical native install does not bind cuVS to its selected RMM runtime" >&2
    exit 1
}
for required in 'CMAKE_CUDA_RUNTIME_LIBRARY=SHARED' 'CUDA_cudart_static_LIBRARY=' 'libcudart\.so' 'cudaMalloc'; do
    rg -Fq "${required}" "${repo_root}/scripts/build_libcuvs.sh" || {
        echo "error: canonical native build does not enforce its dynamic CUDA runtime contract: ${required}" >&2
        exit 1
    }
done

echo "checked-in generated binding contract OK"
