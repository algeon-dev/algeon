generate_cuvs() {
  scripts/ci/check_native_sources.sh
  local dlpack_include="${DLPACK_INCLUDE_DIR:-${repo_root}/target/native/cuvs-build/_deps/dlpack-src/include}"
  [[ -f "${dlpack_include}/dlpack/dlpack.h" ]] || {
    printf "error: DLPack headers are missing under '%s'; build cuVS or set DLPACK_INCLUDE_DIR\n" \
      "${dlpack_include}" >&2
    return 1
  }

  local output=components/cuvs/algeon-cuvs-sys/src/bindings.rs
  local temporary
  local -a clang_args=(
    -I "${repo_root}/components/cuvs/algeon-cuvs-sys/bindgen-stubs"
    -I "${repo_root}/components/cuvs/cuvs/c/include"
    -I "${dlpack_include}"
  )
  if [[ -d "${CUDA_HOME:-}/include" ]]; then
    clang_args+=( -I "${CUDA_HOME}/include" )
  fi
  temporary="$(mktemp "${output}.tmp.XXXXXX")"
  if ! "${bindgen_bin}" components/cuvs/algeon-cuvs-sys/cuvs_c_wrapper.h \
    --must-use-type 'cuvsError_t' \
    --allowlist-function 'cuvs.*' \
    --allowlist-type '(cuvs|DL).*' \
    --rustified-enum '(cuvs|DL).*' \
    --blocklist-item 'cuda.*' \
    --blocklist-item 'CUstream_st' \
    --raw-line 'use crate::{cudaDataType_t, cudaStream_t};' \
    --rustfmt-configuration-file "${repo_root}/components/cuvs/algeon-cuvs-sys/bindings/rustfmt.toml" \
    -- "${clang_args[@]}" >"${temporary}"; then
    rm -f "${temporary}"
    return 1
  fi
  install_generated "${temporary}" "${output}"
}

generate_cugraph() {
  scripts/ci/check_native_sources.sh
  local output=components/cugraph/algeon-cugraph-sys/src/bindings.rs
  local temporary
  local cugraph_include="${repo_root}/components/cugraph/cugraph/cpp/include"
  local cudf_include="${CUDF_INSTALL_DIR:-${repo_root}/target/native/cudf-install}/include"
  [[ -f "${cugraph_include}/cugraph_c/algorithms.h" ]] || {
    printf "error: cuGraph headers are missing under '%s'; initialize the cuGraph submodule\n" \
      "${cugraph_include}" >&2
    return 1
  }
  [[ -f "${cudf_include}/cudf_rust/memory_resource.h" ]] || {
    printf "error: cuDF Rust shim headers are missing under '%s'; run scripts/build/build_libcudf.sh or set CUDF_INSTALL_DIR\n" \
      "${cudf_include}" >&2
    return 1
  }
  temporary="$(mktemp "${output}.tmp.XXXXXX")"
  if ! {
    printf '%s\n' "// Generated by scripts/dev/bindings.sh cugraph with bindgen-cli ${bindgen_version}."
    printf '%s\n' '// DO NOT EDIT. Run scripts/dev/bindings.sh cugraph to regenerate.'
    printf '\n'
    "${bindgen_bin}" components/cugraph/algeon-cugraph-sys/wrapper.h \
      --allowlist-function 'cugraph_.*' \
      --allowlist-type 'cugraph_.*' \
      --allowlist-type 'bool_.*' \
      --allowlist-type 'data_type_id_.*' \
      --allowlist-var 'CUGRAPH_.*' \
      --with-derive-eq \
      --with-derive-hash \
      --newtype-enum 'cugraph_error_code_.*' \
      --newtype-enum 'cugraph_allocation_source_.*' \
      --newtype-enum 'cugraph_error_failure_source_.*' \
      --newtype-enum 'bool_.*' \
      --newtype-enum 'data_type_id_.*' \
      --formatter rustfmt \
      -- \
      -I "${cugraph_include}" \
      -I "${cudf_include}"
  } >"${temporary}"; then
    rm -f "${temporary}"
    return 1
  fi
  install_generated "${temporary}" "${output}"
}

case "${component}" in
  cudf)
    generate_cudf components/cudf/algeon-cudf-sys/src/bindings.rs production
    generate_cudf components/cudf/algeon-cudf-sys/src/test_support.rs test-support
    ;;
  cugraph) generate_cugraph ;;
  cuml)
    generate_cuml components/cuml/algeon-cuml-sys/src/bindings.rs production
    generate_cuml components/cuml/algeon-cuml-sys/src/test_support.rs test-support
    ;;
  cuvs) generate_cuvs ;;
esac
