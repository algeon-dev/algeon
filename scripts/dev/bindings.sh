#!/usr/bin/env bash
set -euo pipefail

readonly repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly bindgen_bin="${BINDGEN:-bindgen}"

usage() {
  printf 'usage: %s <cudf|cugraph|cuml|cuvs> [--check]\n' "${0##*/}" >&2
}

[[ $# -ge 1 && $# -le 2 ]] || {
  usage
  exit 2
}
component=$1
check=0
case "${2:-}" in
  '') ;;
  --check) check=1 ;;
  *)
    usage
    exit 2
    ;;
esac
case "${component}" in
  cudf | cugraph | cuml | cuvs) ;;
  *)
    usage
    exit 2
    ;;
esac

manifest="components/${component}/algeon-${component}-sys/Cargo.toml"
bindgen_version=$(python3 - "${repo_root}/${manifest}" <<'PY'
import sys
import tomllib

with open(sys.argv[1], "rb") as source:
    print(tomllib.load(source)["package"]["metadata"]["bindgen-cli"]["version"])
PY
)

if ! installed_version="$(${bindgen_bin} --version)"; then
  printf 'error: bindgen-cli %s is required; install with: cargo install --locked bindgen-cli --version %s\n' \
    "${bindgen_version}" "${bindgen_version}" >&2
  exit 1
fi
[[ "${installed_version}" == "bindgen ${bindgen_version}" ]] || {
  printf 'error: expected bindgen %s, found %s\n' "${bindgen_version}" "${installed_version}" >&2
  exit 1
}

if [[ -z "${RUSTFMT:-}" ]]; then
  export RUSTFMT="$(rustup which rustfmt --toolchain nightly)"
fi

cd "${repo_root}"

install_generated() {
  local temporary=$1
  local output=$2
  chmod 0644 "${temporary}"
  if ((check)); then
    if ! cmp -s "${temporary}" "${output}"; then
      printf 'error: %s is stale; run scripts/dev/bindings.sh %s\n' "${output}" "${component}" >&2
      diff -u "${output}" "${temporary}" | sed -n '1,200p' >&2 || true
      rm -f "${temporary}"
      return 1
    fi
    rm -f "${temporary}"
  else
    mv "${temporary}" "${output}"
  fi
}

generate_cudf() {
  local output=$1
  local kind=$2
  local temporary
  temporary="$(mktemp "${output}.tmp.XXXXXX")"
  if ! {
    printf '%s\n' "// Generated by scripts/dev/bindings.sh cudf with bindgen-cli ${bindgen_version}."
    printf '%s\n' '// DO NOT EDIT. Run scripts/dev/bindings.sh cudf to regenerate.'
    printf '\n'

    if [[ "${kind}" == production ]]; then
      "${bindgen_bin}" components/cudf/algeon-cudf-sys/bindings/wrapper.h \
        --allowlist-function '^cudf_.*' \
        --allowlist-type '^cudf_.*' \
        --allowlist-var '^CUDF_.*' \
        --default-enum-style consts \
        --no-prepend-enum-name \
        --no-layout-tests \
        --use-core \
        --ctypes-prefix core::ffi \
        --rust-target 1.95 \
        --rust-edition 2024 \
        --sort-semantically \
        --merge-extern-blocks \
        --formatter rustfmt \
        -- -I components/cudf/algeon-cudf-sys/native/include -xc
    else
      "${bindgen_bin}" components/cudf/algeon-cudf-sys/bindings/wrapper.h \
        --allowlist-function '^cudf_test_.*' \
        --allowlist-type '^cudf_test_.*' \
        --allowlist-var '^CUDF_TEST_.*' \
        --blocklist-type '^cudf_(status_t|stream_handle|memory_resource_handle|memory_manager_handle|column_view_handle|type_id_t)(_state)?$' \
        --default-enum-style consts \
        --no-prepend-enum-name \
        --no-layout-tests \
        --use-core \
        --ctypes-prefix core::ffi \
        --rust-target 1.95 \
        --rust-edition 2024 \
        --sort-semantically \
        --merge-extern-blocks \
        --formatter rustfmt \
        --raw-line 'use crate::*;' \
        -- -DCUDF_RUST_BINDINGS_TEST_SUPPORT -I components/cudf/algeon-cudf-sys/native/include -xc
    fi
  } >"${temporary}"; then
    rm -f "${temporary}"
    return 1
  fi
  install_generated "${temporary}" "${output}"
}

