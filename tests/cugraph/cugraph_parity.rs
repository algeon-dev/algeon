//! Registry-driven cuGraph parity harness.
//!
//! Default `cargo test --features cugraph` exercises the CPU-only path:
//! dataset SHA-256 verification, parity spec shape, and oracle JSON
//! header validation when a checked-in file is present. The actual GPU
//! parity comparisons are landed alongside Python cuGraph availability
//! and run under `--include-ignored` with the GPU lock held; that work
//! is left as a follow-up. See
//! `docs/plan/2026-05-20-cugraph-rs-full-api-support-plan.md` (Testing
//! redesign section) for the full design.

#[path = "cugraph_parity/compare.rs"]
mod compare;
#[path = "cugraph_parity/datasets.rs"]
mod datasets;
#[path = "cugraph_parity/oracle.rs"]
mod oracle;

use datafusion_nexus::{
    CUGRAPH_OPERATION_REGISTRY, CugraphAlgorithm,
    graph_sql::parity::{CUGRAPH_PARITY_SPECS, OracleLookup, ParityTruthSource, data_root, load_ref_csv_vertex_list},
};

#[test]
fn parity_manifest_loads_and_dataset_checksums_match() {
    let loaded =
        datasets::load_and_verify().expect("cuGraph manifest must load and every vendored dataset SHA-256 must match");
    assert!(
        loaded.manifest.datasets.iter().any(|d| d.id == "karate"),
        "vendored manifest must include the karate dataset",
    );
}

#[test]
fn parity_specs_reference_existing_datasets() {
    let loaded = datasets::load_and_verify().expect("manifest must load");
    for spec in CUGRAPH_PARITY_SPECS {
        assert!(
            loaded.manifest.dataset(spec.dataset).is_some(),
            "parity spec '{}' references unknown dataset '{}'",
            spec.label,
            spec.dataset,
        );
    }
}

#[test]
fn parity_specs_cover_baseline_algorithms() {
    let mut algorithms: Vec<_> = CUGRAPH_PARITY_SPECS.iter().map(|spec| spec.algorithm).collect();
    algorithms.sort();
    algorithms.dedup();
    let registered: Vec<_> = CUGRAPH_OPERATION_REGISTRY.iter().map(|entry| entry.algorithm).collect();
    let mut sorted_registered = registered;
    sorted_registered.sort();
    assert_eq!(
        algorithms, sorted_registered,
        "Milestone 1a parity registry must cover every currently registered cuGraph algorithm exactly once",
    );
    assert!(
        CUGRAPH_PARITY_SPECS
            .iter()
            .any(|spec| spec.algorithm == CugraphAlgorithm::PageRank && spec.dataset == "karate"),
        "Milestone 1a must keep at least the karate PageRank entry as the canonical baseline",
    );
}

#[test]
fn parity_specs_declare_a_comparator_family() {
    for spec in CUGRAPH_PARITY_SPECS {
        let label = compare::family_label(spec.comparator);
        assert!(!label.is_empty(), "spec '{}' has an empty comparator family label", spec.label,);
    }
}

#[test]
fn parity_oracle_lookup_reports_missing_with_refresh_hint() {
    let loaded = datasets::load_and_verify().expect("manifest must load");
    let mut missing = Vec::new();
    let mut mismatches = Vec::new();
    let mut present = 0usize;
    for spec in CUGRAPH_PARITY_SPECS {
        // Every spec carries an `oracle_relpath` — for `OracleJson`
        // truth it is the primary ground truth; for `RefCsv` truth it
        // is a secondary cross-check generated by Python cuGraph. Look
        // it up unconditionally so a missing secondary oracle for a
        // RefCsv spec still surfaces as "needs refresh".
        match oracle::lookup(&loaded.data_root, &loaded.manifest, spec) {
            OracleLookup::Present { .. } => present += 1,
            OracleLookup::Missing { path } => {
                missing.push(format!(
                    "  - {label}: oracle missing at {path}\n    {hint}",
                    label = spec.label,
                    path = path.display(),
                    hint = oracle::refresh_hint(&loaded.data_root, spec),
                ));
            },
            OracleLookup::Invalid { path, reason } | OracleLookup::Mismatch { path, reason } => {
                mismatches.push(format!(
                    "  - {label}: oracle at {path} rejected: {reason}",
                    label = spec.label,
                    path = path.display(),
                ));
            },
        }
        // RefCsv-truth specs additionally require their primary
        // reference file to be present and parseable on disk. Surface
        // a missing/invalid ref CSV as a hard test failure: the GPU
        // comparator path (Milestone 1b) relies on this file being
        // loadable, and silently degrading would hide that gap.
        if let ParityTruthSource::RefCsv { path } = spec.truth_source
            && let Err(error) = load_ref_csv_vertex_list(&loaded.data_root, path)
        {
            mismatches.push(format!(
                "  - {label}: ref CSV at {path} rejected: {error}",
                label = spec.label,
                path = path,
            ));
        }
    }
    assert!(mismatches.is_empty(), "checked-in oracle JSON disagrees with parity spec:\n{}", mismatches.join("\n"),);
    if !missing.is_empty() {
        // Milestone 1a lands the infrastructure ahead of running Python
        // cuGraph against the vendored datasets. The harness reports a
        // structured "needs refresh" message rather than failing the
        // default CPU-only run, but emits it on stderr so refreshes
        // are visible in CI logs.
        eprintln!(
            "cuGraph parity harness: {} oracle JSON file(s) need refresh; {} present.\n{}",
            missing.len(),
            present,
            missing.join("\n"),
        );
    }
}

#[test]
fn parity_data_root_lives_under_workspace_fixture_dir() {
    // `data_root` honors `CUDF_CUGRAPH_DATA_ROOT` so refresh tooling can
    // point at a staging fixture path. The default-case assertion only
    // runs when the override is absent.
    if std::env::var_os("CUDF_CUGRAPH_DATA_ROOT").is_some() {
        return;
    }
    let root = data_root();
    let suffix = std::path::Path::new("fixture").join("data").join("cugraph");
    assert!(root.ends_with(suffix), "parity data root unexpected: {}", root.display());
}
