def selected_specs(args: argparse.Namespace) -> list[DatasetSpec]:
    if args.list:
        return []
    if args.dataset:
        return [DATASETS[name] for name in args.dataset]
    tier = args.tier if args.tier is not None else 1
    return [spec for spec in DATASETS.values() if spec.tier == tier]


