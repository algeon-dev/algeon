def require_positive(name: str, value: int) -> None:
    if value < 1:
        raise SystemExit(f"{name} must be >= 1")


def run_command(command: list[str], cwd: Path | None = None) -> None:
    print("[snap-ingest] running:", " ".join(shlex.quote(part) for part in command), flush=True)
    subprocess.run(command, cwd=cwd, check=True)


def run_bash(script: str) -> None:
    print("[snap-ingest] running bash pipeline", flush=True)
    subprocess.run(["bash", "-lc", script], check=True)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(8 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def raw_file_name(url: str) -> str:
    return url.rstrip("/").split("/")[-1]


def download(url: str, path: Path, no_download: bool) -> dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        return {"path": str(path), "bytes": path.stat().st_size, "sha256": sha256(path), "downloaded": False}
    if no_download:
        raise SystemExit(f"missing raw SNAP file and --no-download was set: {path}")
    partial = path.with_suffix(path.suffix + ".part")
    run_command(["curl", "-L", "--fail", "--continue-at", "-", "--output", str(partial), url])
    partial.rename(path)
    return {"path": str(path), "bytes": path.stat().st_size, "sha256": sha256(path), "downloaded": True}


def dataset_root(out_root: Path, spec: DatasetSpec, max_edges: int) -> Path:
    suffix = f"_sample_edges{max_edges}" if max_edges > 0 else ""
    return out_root / spec.dataset_id / f"v1{suffix}"


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


