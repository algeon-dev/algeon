def validate_resume_manifest(root: Path, args: argparse.Namespace) -> dict[str, Any] | None:
    if args.overwrite:
        return None
    manifest_path = root / "manifest.json"
    existing_parquet = [edge_parquet_path(root, order) for order in ("src", "dst") if edge_parquet_path(root, order).exists()]
    if not existing_parquet:
        return None
    if not manifest_path.exists():
        paths = ", ".join(str(path) for path in existing_parquet)
        raise SystemExit(
            f"{root}: existing Parquet cannot be safely reused without manifest.json; "
            f"pass --overwrite to regenerate ({paths})"
        )
    manifest = read_json(manifest_path)
    for key, current in (("row_group_size", args.row_group_size), ("bucket_width", args.bucket_width)):
        previous = manifest.get(key)
        if previous != current:
            raise SystemExit(
                f"{root}: existing Parquet was generated with {key}={previous}, "
                f"but this run requested {key}={current}; pass --overwrite to regenerate"
            )
    return manifest


def sort_edge_file(
    raw_path: Path,
    target: Path,
    order: str,
    args: argparse.Namespace,
) -> None:
    if target.exists() and not args.overwrite:
        print(f"[snap-ingest] keeping existing sorted TSV: {target}", flush=True)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    sort_tmp = (args.sort_temp_dir or (args.out_root / "_sort_tmp")).resolve()
    sort_tmp.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    if temporary.exists():
        temporary.unlink()
    key_flags = {
        "src": "-k2,2n -k3,3n -k1,1n",
        "dst": "-k3,3n -k2,2n -k1,1n",
    }[order]
    limit_clause = ""
    if args.max_edges > 0:
        # Avoid `head` in a pipe because early SIGPIPE from gzip interacts poorly with pipefail.
        limit_clause = f" -v limit={args.max_edges} "
        awk_program = r"""BEGIN { c = 0 } NF >= 2 && $1 !~ /^#/ { print c "\t" $1 "\t" $2; c++; if (limit > 0 && c >= limit) exit }"""
    else:
        awk_program = r"""BEGIN { c = 0 } NF >= 2 && $1 !~ /^#/ { print c "\t" $1 "\t" $2; c++ }"""
    script = (
        "set -euo pipefail\n"
        f"gzip -cd {shlex.quote(str(raw_path))} | "
        f"awk {limit_clause}{shlex.quote(awk_program)} | "
        f"LC_ALL=C sort -S {shlex.quote(args.sort_memory)} --parallel={args.sort_parallel} "
        f"-T {shlex.quote(str(sort_tmp))} {key_flags} "
        f"> {shlex.quote(str(temporary))}\n"
        f"mv {shlex.quote(str(temporary))} {shlex.quote(str(target))}\n"
    )
    run_bash(script)


def sort_small_edge_sample(raw_path: Path, target: Path, order: str, max_edges: int) -> None:
    rows: list[tuple[int, int, int]] = []
    with gzip.open(raw_path, "rt", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            parts = stripped.split()
            if len(parts) < 2:
                continue
            edge_id = len(rows)
            rows.append((edge_id, int(parts[0]), int(parts[1])))
            if len(rows) >= max_edges:
                break
    if order == "src":
        rows.sort(key=lambda row: (row[1], row[2], row[0]))
    else:
        rows.sort(key=lambda row: (row[2], row[1], row[0]))
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8") as fh:
        for edge_id, src, dst in rows:
            fh.write(f"{edge_id}\t{src}\t{dst}\n")


def sort_profile_file(raw_path: Path, target: Path, args: argparse.Namespace) -> None:
    if target.exists() and not args.overwrite:
        print(f"[snap-ingest] keeping existing sorted profile TSV: {target}", flush=True)
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    sort_tmp = (args.sort_temp_dir or (args.out_root / "_sort_tmp")).resolve()
    sort_tmp.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(target.suffix + ".tmp")
    if temporary.exists():
        temporary.unlink()
    awk_program = r"""NF >= 1 && $1 !~ /^#/ { print $0 }"""
    script = (
        "set -euo pipefail\n"
        f"gzip -cd {shlex.quote(str(raw_path))} | "
        f"awk {shlex.quote(awk_program)} | "
        f"LC_ALL=C sort -S {shlex.quote(args.sort_memory)} --parallel={args.sort_parallel} "
        f"-T {shlex.quote(str(sort_tmp))} -k1,1n "
        f"> {shlex.quote(str(temporary))}\n"
        f"mv {shlex.quote(str(temporary))} {shlex.quote(str(target))}\n"
    )
    run_bash(script)


def sort_small_profile_sample(raw_path: Path, target: Path, max_profiles: int, overwrite: bool) -> None:
    if target.exists() and not overwrite:
        print(f"[snap-ingest] keeping existing sorted profile sample TSV: {target}", flush=True)
        return
    rows: list[tuple[int, str]] = []
    with gzip.open(raw_path, "rt", encoding="utf-8", errors="replace", newline="") as fh:
        for line in fh:
            stripped = line.rstrip("\r\n")
            if not stripped:
                continue
            parts = stripped.split("\t", 1)
            try:
                user_id = int(parts[0])
            except ValueError as error:
                raise SystemExit(f"profile sample row has non-integer user_id: {parts[0]!r}") from error
            rows.append((user_id, stripped))
            if len(rows) >= max_profiles:
                break
    rows.sort(key=lambda row: row[0])
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8") as fh:
        for _, row in rows:
            fh.write(f"{row}\n")


def make_edge_table(
    edge_ids: list[int],
    src: list[int],
    dst: list[int],
    bucket_width: int,
) -> pa.Table:
    return pa.table(
        {
            "edge_id": pa.array(edge_ids, type=pa.int64()),
            "src": pa.array(src, type=pa.int64()),
            "dst": pa.array(dst, type=pa.int64()),
            "weight": pa.array([1.0] * len(src), type=pa.float64()),
            "src_bucket": pa.array([value // bucket_width for value in src], type=pa.int32()),
            "dst_bucket": pa.array([value // bucket_width for value in dst], type=pa.int32()),
        },
        schema=EDGE_SCHEMA,
    )


def make_edge_table_from_arrays(edge_ids: pa.ChunkedArray | pa.Array, src: pa.ChunkedArray | pa.Array, dst: pa.ChunkedArray | pa.Array, bucket_width: int) -> pa.Table:
    rows = len(src)
    src_bucket = pc.cast(pc.divide_checked(src, pa.scalar(bucket_width, type=pa.int64())), pa.int32())
    dst_bucket = pc.cast(pc.divide_checked(dst, pa.scalar(bucket_width, type=pa.int64())), pa.int32())
    return pa.table(
        {
            "edge_id": edge_ids,
            "src": src,
            "dst": dst,
            "weight": pa.repeat(pa.scalar(1.0, type=pa.float64()), rows),
            "src_bucket": src_bucket,
            "dst_bucket": dst_bucket,
        },
        schema=EDGE_SCHEMA,
    )


def write_edges_parquet(
    sorted_tsv: Path,
    parquet_path: Path,
    args: argparse.Namespace,
) -> dict[str, Any]:
    if parquet_path.exists() and not args.overwrite:
        return parquet_metadata(parquet_path)
    if parquet_path.exists():
        parquet_path.unlink()
    parquet_path.parent.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    rows = 0
    max_vertex = -1
    min_src = math.inf
    max_src = -1
    min_dst = math.inf
    max_dst = -1
    csv_reader = pacsv.open_csv(
        sorted_tsv,
        read_options=pacsv.ReadOptions(
            column_names=["edge_id", "src", "dst"],
            block_size=64 * 1024 * 1024,
            use_threads=True,
        ),
        parse_options=pacsv.ParseOptions(delimiter="\t"),
        convert_options=pacsv.ConvertOptions(
            column_types={"edge_id": pa.int64(), "src": pa.int64(), "dst": pa.int64()},
        ),
    )
    writer = pq.ParquetWriter(
        parquet_path,
        EDGE_SCHEMA,
        compression="zstd",
        version="2.6",
        write_statistics=True,
    )
    try:
        for batch in csv_reader:
            table = pa.Table.from_batches([batch])
            edge_ids = table["edge_id"]
            src_values = table["src"]
            dst_values = table["dst"]
            batch_rows = table.num_rows
            rows += batch_rows
            batch_min_src = int(pc.min(src_values).as_py())
            batch_max_src = int(pc.max(src_values).as_py())
            batch_min_dst = int(pc.min(dst_values).as_py())
            batch_max_dst = int(pc.max(dst_values).as_py())
            min_src = min(min_src, batch_min_src)
            max_src = max(max_src, batch_max_src)
            min_dst = min(min_dst, batch_min_dst)
            max_dst = max(max_dst, batch_max_dst)
            max_vertex = max(max_vertex, batch_max_src, batch_max_dst)
            writer.write_table(
                make_edge_table_from_arrays(edge_ids, src_values, dst_values, args.bucket_width),
                row_group_size=args.row_group_size,
            )
    finally:
        writer.close()
    metadata = parquet_metadata(parquet_path)
    metadata.update(
        {
            "rows": rows,
            "max_vertex_id": max_vertex,
            "min_src": None if rows == 0 else int(min_src),
            "max_src": None if rows == 0 else int(max_src),
            "min_dst": None if rows == 0 else int(min_dst),
            "max_dst": None if rows == 0 else int(max_dst),
            "elapsed_ms": (time.perf_counter() - started) * 1000.0,
        }
    )
    return metadata


def parquet_metadata(path: Path) -> dict[str, Any]:
    meta = pq.ParquetFile(path).metadata
    row_groups: list[dict[str, Any]] = []
    schema = pq.ParquetFile(path).schema_arrow
    column_names = schema.names
    for index in range(min(meta.num_row_groups, 8)):
        row_group = meta.row_group(index)
        entry: dict[str, Any] = {"index": index, "rows": row_group.num_rows}
        for column in ("src", "dst", "community_id", "vertex", "user_id", "age", "completion_percentage"):
            if column not in column_names:
                continue
            column_index = column_names.index(column)
            stats = row_group.column(column_index).statistics
            if stats is not None and stats.has_min_max:
                entry[f"{column}_min"] = int(stats.min)
                entry[f"{column}_max"] = int(stats.max)
        row_groups.append(entry)
    return {
        "path": str(path),
        "bytes": path.stat().st_size,
        "num_rows": meta.num_rows,
        "num_row_groups": meta.num_row_groups,
        "schema": column_names,
        "sample_row_groups": row_groups,
    }


def profile_parquet_path(root: Path) -> Path:
    return root / "parquet" / "profiles_by_user_id.parquet"


def effective_max_profiles(args: argparse.Namespace) -> int:
    if args.max_profiles is not None:
        return args.max_profiles
    if args.max_edges > 0:
        return args.max_edges
    return 0


def nullable_text(value: str) -> str | None:
    text = value.strip()
    if not text or text.lower() == "null":
        return None
    return text


def nullable_int(value: str, column_name: str, line_number: int) -> int | None:
    text = nullable_text(value)
    if text is None:
        return None
    try:
        return int(text)
    except ValueError as error:
        raise SystemExit(f"profile line {line_number}: expected integer in {column_name}, got {text!r}") from error


def profile_region_levels(region: str | None) -> tuple[str | None, str | None]:
    if region is None:
        return (None, None)
    parts = [part.strip() for part in region.split(",", 1)]
    level_1 = parts[0] if parts and parts[0] else None
    level_2 = parts[1] if len(parts) > 1 and parts[1] else None
    return (level_1, level_2)


def normalize_profile_parts(parts: list[str]) -> tuple[list[str], bool, bool]:
    source_columns = len(PROFILE_SOURCE_COLUMNS)
    while len(parts) > source_columns and parts[-1] == "":
        parts.pop()
    was_short = len(parts) < source_columns
    was_long = len(parts) > source_columns
    if was_short:
        parts.extend([""] * (source_columns - len(parts)))
    elif was_long:
        parts = parts[: source_columns - 1] + ["\t".join(parts[source_columns - 1 :])]
    return (parts, was_short, was_long)


def append_profile_row(columns: dict[str, list[Any]], parts: list[str], line_number: int) -> tuple[int, int | None]:
    mapped = dict(zip(PROFILE_SOURCE_COLUMNS, parts, strict=True))
    user_id = nullable_int(mapped["user_id"], "user_id", line_number)
    if user_id is None:
        raise SystemExit(f"profile line {line_number}: user_id is required")
    is_public = nullable_int(mapped["public"], "public", line_number)
    completion_percentage = nullable_int(mapped["completion_percentage"], "completion_percentage", line_number)
    gender = nullable_int(mapped["gender"], "gender", line_number)
    age = nullable_int(mapped["AGE"], "AGE", line_number)

    region = nullable_text(mapped["region"])
    region_level_1, region_level_2 = profile_region_levels(region)
    age_bucket = (age // 10) * 10 if age is not None and age > 0 else None

    special_values: dict[str, Any] = {
        "user_id": user_id,
        "is_public": is_public,
        "completion_percentage": completion_percentage,
        "gender": gender,
        "region": region,
        "last_login": nullable_text(mapped["last_login"]),
        "registration": nullable_text(mapped["registration"]),
        "age": age,
        "region_level_1": region_level_1,
        "region_level_2": region_level_2,
        "age_bucket": age_bucket,
    }
    source_to_output = dict(zip(PROFILE_SOURCE_COLUMNS, PROFILE_OUTPUT_COLUMNS[: len(PROFILE_SOURCE_COLUMNS)], strict=True))
    for source_name, output_name in source_to_output.items():
        if output_name in special_values:
            continue
        special_values[output_name] = nullable_text(mapped[source_name])
    for column in PROFILE_OUTPUT_COLUMNS:
        columns[column].append(special_values[column])
    return (user_id, age)


def empty_profile_columns() -> dict[str, list[Any]]:
    return {column: [] for column in PROFILE_OUTPUT_COLUMNS}


def write_profile_batch(writer: pq.ParquetWriter, columns: dict[str, list[Any]], row_group_size: int) -> None:
    if not columns["user_id"]:
        return
    table = pa.table(
        {field.name: pa.array(columns[field.name], type=field.type) for field in PROFILE_SCHEMA},
        schema=PROFILE_SCHEMA,
    )
    writer.write_table(table, row_group_size=row_group_size)
    for values in columns.values():
        values.clear()


def write_profile_table(
    raw_path: Path,
    root: Path,
    args: argparse.Namespace,
) -> dict[str, Any]:
    parquet_path = profile_parquet_path(root)
    if parquet_path.exists() and not args.overwrite:
        metadata = parquet_metadata(parquet_path)
        metadata.update({"rows": metadata["num_rows"], "source_columns": PROFILE_SOURCE_COLUMNS, "sort_order": ["user_id"]})
        return metadata
    if parquet_path.exists():
        parquet_path.unlink()
    parquet_path.parent.mkdir(parents=True, exist_ok=True)

    max_profiles = effective_max_profiles(args)
    sorted_path = sorted_profile_tsv_path(root)
    if max_profiles > 0:
        sort_small_profile_sample(raw_path, sorted_path, max_profiles, args.overwrite)
    else:
        sort_profile_file(raw_path, sorted_path, args)
    profile_batch_rows = min(args.row_group_size, 131_072)
    started = time.perf_counter()
    rows = 0
    rows_with_age = 0
    short_rows = 0
    long_rows = 0
    min_user_id = math.inf
    max_user_id = -1
    columns = empty_profile_columns()
    writer = pq.ParquetWriter(
        parquet_path,
        PROFILE_SCHEMA,
        compression="zstd",
        version="2.6",
        write_statistics=True,
    )
    try:
        with sorted_path.open("r", encoding="utf-8", errors="replace", newline="") as fh:
            for line_number, line in enumerate(fh, start=1):
                stripped = line.rstrip("\r\n")
                if not stripped:
                    continue
                parts, was_short, was_long = normalize_profile_parts(stripped.split("\t"))
                short_rows += int(was_short)
                long_rows += int(was_long)
                user_id, age = append_profile_row(columns, parts, line_number)
                rows += 1
                rows_with_age += int(age is not None and age > 0)
                min_user_id = min(min_user_id, user_id)
                max_user_id = max(max_user_id, user_id)
                if len(columns["user_id"]) >= profile_batch_rows:
                    write_profile_batch(writer, columns, args.row_group_size)
        write_profile_batch(writer, columns, args.row_group_size)
    finally:
        writer.close()

    metadata = parquet_metadata(parquet_path)
    metadata.update(
        {
            "rows": rows,
            "max_profiles": None if max_profiles <= 0 else max_profiles,
            "rows_with_age": rows_with_age,
            "short_rows_padded": short_rows,
            "long_rows_joined_into_more": long_rows,
            "min_user_id": None if rows == 0 else int(min_user_id),
            "max_user_id": None if rows == 0 else int(max_user_id),
            "elapsed_ms": (time.perf_counter() - started) * 1000.0,
            "source_columns": PROFILE_SOURCE_COLUMNS,
            "sort_order": ["user_id"],
        }
    )
    remove_if_requested(sorted_path, args.keep_sorted_tsv)
    return metadata


def write_community_tables(
    raw_path: Path,
    root: Path,
    args: argparse.Namespace,
) -> dict[str, Any]:
    membership_path = root / "parquet" / "communities_membership.parquet"
    summary_path = root / "parquet" / "communities_summary.parquet"
    if membership_path.exists() and summary_path.exists() and not args.overwrite:
        membership = parquet_metadata(membership_path)
        summary = parquet_metadata(summary_path)
        return {
            "communities": summary["num_rows"],
            "membership_rows": membership["num_rows"],
            "membership": membership,
            "summary": summary,
        }
    for path in (membership_path, summary_path):
        if path.exists():
            path.unlink()
        path.parent.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    community_ids: list[int] = []
    vertices: list[int] = []
    ordinals: list[int] = []
    sizes: list[int] = []
    summary_ids: list[int] = []
    summary_sizes: list[int] = []
    community_count = 0
    membership_rows = 0
    membership_writer = pq.ParquetWriter(
        membership_path,
        COMMUNITY_MEMBERSHIP_SCHEMA,
        compression="zstd",
        version="2.6",
        write_statistics=True,
    )
    summary_writer = pq.ParquetWriter(
        summary_path,
        COMMUNITY_SUMMARY_SCHEMA,
        compression="zstd",
        version="2.6",
        write_statistics=True,
    )
    try:
        with gzip.open(raw_path, "rt", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue
                members = [int(part) for part in stripped.split()]
                community_id = community_count
                community_size = len(members)
                summary_ids.append(community_id)
                summary_sizes.append(community_size)
                for ordinal, vertex in enumerate(members):
                    community_ids.append(community_id)
                    vertices.append(vertex)
                    ordinals.append(ordinal)
                    sizes.append(community_size)
                community_count += 1
                membership_rows += community_size
                if len(vertices) >= args.row_group_size:
                    write_membership_batch(membership_writer, community_ids, vertices, ordinals, sizes, args.row_group_size)
                    community_ids.clear()
                    vertices.clear()
                    ordinals.clear()
                    sizes.clear()
                if len(summary_ids) >= args.row_group_size:
                    write_summary_batch(summary_writer, summary_ids, summary_sizes, args.row_group_size)
                    summary_ids.clear()
                    summary_sizes.clear()
        if vertices:
            write_membership_batch(membership_writer, community_ids, vertices, ordinals, sizes, args.row_group_size)
        if summary_ids:
            write_summary_batch(summary_writer, summary_ids, summary_sizes, args.row_group_size)
    finally:
        membership_writer.close()
        summary_writer.close()
    return {
        "communities": community_count,
        "membership_rows": membership_rows,
        "elapsed_ms": (time.perf_counter() - started) * 1000.0,
        "membership": parquet_metadata(membership_path),
        "summary": parquet_metadata(summary_path),
    }


def write_membership_batch(
    writer: pq.ParquetWriter,
    community_ids: list[int],
    vertices: list[int],
    ordinals: list[int],
    sizes: list[int],
    row_group_size: int,
) -> None:
    table = pa.table(
        {
            "community_id": pa.array(community_ids, type=pa.int64()),
            "vertex": pa.array(vertices, type=pa.int64()),
            "member_ordinal": pa.array(ordinals, type=pa.int32()),
            "community_size": pa.array(sizes, type=pa.int32()),
        },
        schema=COMMUNITY_MEMBERSHIP_SCHEMA,
    )
    writer.write_table(table, row_group_size=row_group_size)


def write_summary_batch(
    writer: pq.ParquetWriter,
    community_ids: list[int],
    sizes: list[int],
    row_group_size: int,
) -> None:
    table = pa.table(
        {
            "community_id": pa.array(community_ids, type=pa.int64()),
            "community_size": pa.array(sizes, type=pa.int32()),
        },
        schema=COMMUNITY_SUMMARY_SCHEMA,
    )
    writer.write_table(table, row_group_size=row_group_size)


def validate_counts(spec: DatasetSpec, edge_meta: dict[str, Any], max_edges: int) -> None:
    if max_edges > 0:
        expected = min(max_edges, spec.expected_edges)
    else:
        expected = spec.expected_edges
    rows = int(edge_meta["num_rows"])
    if rows != expected:
        raise SystemExit(f"{spec.dataset_id}: expected {expected:,} edge rows, got {rows:,} in {edge_meta['path']}")


def remove_if_requested(path: Path, keep: bool) -> None:
    if not keep and path.exists():
        path.unlink()


def generate_dataset(spec: DatasetSpec, args: argparse.Namespace) -> dict[str, Any]:
    root = dataset_root(args.out_root.resolve(), spec, args.max_edges)
    raw_root = args.out_root.resolve() / "raw"
    edge_raw = raw_root / raw_file_name(spec.edge_url)
    community_raw = raw_root / raw_file_name(spec.community_url) if spec.community_url else None
    profile_raw = raw_root / raw_file_name(spec.profile_url) if spec.profile_url else None
    print(f"[snap-ingest] dataset={spec.dataset_id} root={root}", flush=True)
    validate_resume_manifest(root, args)

    edge_download = download(spec.edge_url, edge_raw, args.no_download)
    community_download = None
    if community_raw and not args.skip_communities:
        community_download = download(spec.community_url or "", community_raw, args.no_download)
    profile_download = None
    if profile_raw and not args.skip_profiles:
        profile_download = download(spec.profile_url or "", profile_raw, args.no_download)
    write_json(root / "source.json", source_metadata(spec, edge_download, community_download, profile_download))

    if args.download_only:
        return {"dataset": spec.dataset_id, "root": str(root), "download_only": True}

    edge_layouts: dict[str, Any] = {}
    for order in parse_orders(args.orders):
        sorted_path = sorted_tsv_path(root, order)
        parquet_path = edge_parquet_path(root, order)
        if parquet_path.exists() and not args.overwrite:
            edge_meta = parquet_metadata(parquet_path)
        else:
            if args.max_edges > 0 and args.max_edges <= 10_000_000:
                if not sorted_path.exists() or args.overwrite:
                    sort_small_edge_sample(edge_raw, sorted_path, order, args.max_edges)
            else:
                sort_edge_file(edge_raw, sorted_path, order, args)
            edge_meta = write_edges_parquet(sorted_path, parquet_path, args)
            remove_if_requested(sorted_path, args.keep_sorted_tsv)
        validate_counts(spec, edge_meta, args.max_edges)
        edge_layouts[order] = {
            "sort_order": ["src", "dst", "edge_id"] if order == "src" else ["dst", "src", "edge_id"],
            "clustered_for": f"{order}-range filters and row-group pruning",
            "parquet": edge_meta,
        }

    community_meta = None
    if community_raw and not args.skip_communities:
        community_meta = write_community_tables(community_raw, root, args)
        if spec.expected_communities is not None and args.max_edges <= 0:
            actual = int(community_meta["communities"])
            if actual != spec.expected_communities:
                raise SystemExit(
                    f"{spec.dataset_id}: expected {spec.expected_communities:,} communities, got {actual:,}"
                )

    profile_meta = None
    if profile_raw and not args.skip_profiles:
        profile_meta = write_profile_table(profile_raw, root, args)
        max_profiles = effective_max_profiles(args)
        if spec.expected_profiles is not None and max_profiles <= 0:
            actual = int(profile_meta["num_rows"])
            if actual != spec.expected_profiles:
                raise SystemExit(f"{spec.dataset_id}: expected {spec.expected_profiles:,} profiles, got {actual:,}")

    sql_registration = {
        f"edges_by_{order}": (
            f"CREATE EXTERNAL TABLE {spec.dataset_id.replace('-', '_')}_edges_by_{order} "
            f"STORED AS PARQUET LOCATION '{edge_parquet_path(root, order)}'"
        )
        for order in edge_layouts
    }
    if profile_meta is not None:
        sql_registration["profiles_by_user_id"] = (
            f"CREATE EXTERNAL TABLE {spec.dataset_id.replace('-', '_')}_profiles "
            f"STORED AS PARQUET LOCATION '{profile_parquet_path(root)}'"
        )

    manifest = {
        "schema_version": 1,
        "generator": "fixture/scripts/graph/snap_ingest.py",
        "generated_at_unix": int(time.time()),
        "repo_root": str(REPO_ROOT),
        "dataset": asdict(spec),
        "root": str(root),
        "row_group_size": args.row_group_size,
        "bucket_width": args.bucket_width,
        "edge_layouts": edge_layouts,
        "communities": community_meta,
        "profiles": profile_meta,
        "sql_registration": sql_registration,
    }
    write_json(root / "manifest.json", manifest)
    return manifest


def main() -> int:
    args = parse_args()
    if args.list:
        print_dataset_list()
        return 0
    require_positive("--row-group-size", args.row_group_size)
    require_positive("--bucket-width", args.bucket_width)
    require_positive("--sort-parallel", args.sort_parallel)
    if args.max_profiles is not None and args.max_profiles < 0:
        raise SystemExit("--max-profiles must be >= 0")
    specs = selected_specs(args)
    args.out_root.mkdir(parents=True, exist_ok=True)
    summaries = []
    for spec in specs:
        started = time.perf_counter()
        manifest = generate_dataset(spec, args)
        summaries.append(
            {
                "dataset": spec.dataset_id,
                "root": manifest.get("root"),
                "elapsed_ms": (time.perf_counter() - started) * 1000.0,
                "download_only": manifest.get("download_only", False),
            }
        )
    write_json(args.out_root / "last_run.json", {"schema_version": 1, "summaries": summaries})
    print(json.dumps({"summaries": summaries}, indent=2), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
