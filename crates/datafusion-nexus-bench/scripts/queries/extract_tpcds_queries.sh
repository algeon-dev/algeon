#!/usr/bin/env bash
# Re-generate crates/datafusion-nexus-bench/src/workload/tpcds_queries.rs from the DuckDB tpcds extension.
#
# Usage:
#   crates/datafusion-nexus-bench/scripts/queries/extract_tpcds_queries.sh [DUCKDB_BINARY]
#
# DUCKDB_BINARY defaults to:
#   1. $DUCKDB env var, if set
#   2. ~/bin/duckdb, if present
#   3. `duckdb` on PATH
#
# The script:
#   1. Resolves DuckDB binary + version.
#   2. Captures datafusion-nexus git rev + working-tree state.
#   3. Runs DuckDB's tpcds extension to dump query_nr 1..99 to per-query files.
#   4. Assembles crates/datafusion-nexus-bench/src/workload/tpcds_queries.rs with a provenance header.
#
# Any deterministic compatibility rewrite (e.g. for DataFusion) must be applied
# in this script and recorded in REWRITE_APPLIED below. Do NOT hand-edit
# crates/datafusion-nexus-bench/src/workload/tpcds_queries.rs — re-run this script instead.

set -euo pipefail

# --- Resolve DuckDB binary ---------------------------------------------------
DUCKDB_BIN="${1:-${DUCKDB:-}}"
if [[ -z "${DUCKDB_BIN}" ]]; then
  if [[ -x "${HOME}/bin/duckdb" ]]; then
    DUCKDB_BIN="${HOME}/bin/duckdb"
  elif command -v duckdb >/dev/null 2>&1; then
    DUCKDB_BIN="$(command -v duckdb)"
  else
    echo "error: duckdb binary not found; pass as arg 1 or set DUCKDB env" >&2
    exit 1
  fi
fi

if [[ ! -x "${DUCKDB_BIN}" ]]; then
  echo "error: duckdb binary not executable: ${DUCKDB_BIN}" >&2
  exit 1
fi

DUCKDB_BIN_ABS="$(readlink -f "${DUCKDB_BIN}")"
DUCKDB_VERSION="$("${DUCKDB_BIN}" --version | head -1)"

# --- Resolve repo paths ------------------------------------------------------
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUT_FILE="${REPO_ROOT}/crates/datafusion-nexus-bench/src/workload/tpcds_queries.rs"

GIT_REV="$(git -C "${REPO_ROOT}" rev-parse HEAD)"
if [[ -n "$(git -C "${REPO_ROOT}" status --porcelain)" ]]; then
  GIT_TREE="dirty"
else
  GIT_TREE="clean"
fi

# Any future compatibility rewrites get appended here. Keep this exact string
# in sync with what the assembler stamps into the generated file.
REWRITE_APPLIED="trailing semicolon and trailing whitespace stripped per query; otherwise vendored verbatim"

# --- Stage extraction --------------------------------------------------------
WORK_DIR="$(mktemp -d -t tpcds_extract.XXXXXX)"
trap 'rm -rf "${WORK_DIR}"' EXIT

EXTRACT_DIR="${WORK_DIR}/queries"
mkdir -p "${EXTRACT_DIR}"

EXTRACT_SQL="INSTALL tpcds; LOAD tpcds;"$'\n'
for q in $(seq 1 99); do
  qid="$(printf 'q%02d' "${q}")"
  EXTRACT_SQL+="COPY (SELECT query FROM tpcds_queries() WHERE query_nr = ${q}) TO '${EXTRACT_DIR}/${qid}.sql' (HEADER false, QUOTE '', DELIMITER '');"$'\n'
done

TMPDB="${WORK_DIR}/extract.duckdb"
echo "[extract_tpcds_queries] running DuckDB extraction (${DUCKDB_VERSION})" >&2
echo "${EXTRACT_SQL}" | "${DUCKDB_BIN}" "${TMPDB}" > /dev/null

# --- Assemble crates/datafusion-nexus-bench/src/workload/tpcds_queries.rs ---------------------------------
EXTRACT_CMD_DESC="duckdb <tmpdb> -c \"INSTALL tpcds; LOAD tpcds; COPY (SELECT query FROM tpcds_queries() WHERE query_nr = N) TO 'qNN.sql' (HEADER false, QUOTE '', DELIMITER '');\" for N in 1..99"

DUCKDB_BIN_ABS="${DUCKDB_BIN_ABS}" \
DUCKDB_VERSION="${DUCKDB_VERSION}" \
EXTRACT_DIR="${EXTRACT_DIR}" \
EXTRACT_CMD_DESC="${EXTRACT_CMD_DESC}" \
GIT_REV="${GIT_REV}" \
GIT_TREE="${GIT_TREE}" \
OUT_FILE="${OUT_FILE}" \
REWRITE_APPLIED="${REWRITE_APPLIED}" \
python3 - <<'PY'
import os, sys

EXTRACT_DIR    = os.environ["EXTRACT_DIR"]
OUT_FILE       = os.environ["OUT_FILE"]
DUCKDB_BIN_ABS = os.environ["DUCKDB_BIN_ABS"]
DUCKDB_VERSION = os.environ["DUCKDB_VERSION"]
GIT_REV        = os.environ["GIT_REV"]
GIT_TREE       = os.environ["GIT_TREE"]
EXTRACT_CMD    = os.environ["EXTRACT_CMD_DESC"]
REWRITE        = os.environ["REWRITE_APPLIED"]

def normalize(body: str) -> str:
    body = body.rstrip()
    if body.endswith(";"):
        body = body[:-1].rstrip()
    return "\n" + body + "\n"

queries = []
for n in range(1, 100):
    qid = f"q{n:02d}"
    path = os.path.join(EXTRACT_DIR, f"{qid}.sql")
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    norm = normalize(text)
    if '"#' in norm:
        sys.exit(f"{qid}: contains '\"#' — raw string boundary collision; extend the assembler to escape")
    queries.append((qid, norm))

header = f"""\
// Vendored TPC-DS query texts.
//
// Source: DuckDB tpcds extension `SELECT query_nr, query FROM tpcds_queries() ORDER BY query_nr`.
// This file is generated by `crates/datafusion-nexus-bench/scripts/queries/extract_tpcds_queries.sh`; do not
// hand-edit individual queries — re-run the extractor instead.
//
// Provenance:
//   duckdb_binary       : {DUCKDB_BIN_ABS}
//   duckdb_version      : {DUCKDB_VERSION}
//   extraction_command  : {EXTRACT_CMD}
//   datafusion_nexus_rev : {GIT_REV}
//   working_tree        : {GIT_TREE}
//   rewrite_applied     : {REWRITE}
//
// Surface mirrors `crates/datafusion-nexus-bench/src/workload/tpch_queries.rs`:
//   - TPCDS_QUERY_COUNT
//   - TPCDS_QUERIES: &[TpcdsQuery]
//   - tpcds_query_ids()
"""

lines = [header, ""]
lines.append(f"pub const TPCDS_QUERY_COUNT: usize = {len(queries)};")
lines.append("")
lines.append("pub const TPCDS_QUERIES: &[TpcdsQuery] = &[")
for qid, sql in queries:
    lines.append("    TpcdsQuery {")
    lines.append(f"        id: \"{qid}\",")
    lines.append("        sql: r#\"" + sql + "\"#,")
    lines.append("    },")
lines.append("];")
lines.append("")
lines.append("pub struct TpcdsQuery {")
lines.append("    pub id: &'static str,")
lines.append("    pub sql: &'static str,")
lines.append("}")
lines.append("")
lines.append("pub fn tpcds_query_ids() -> impl Iterator<Item = &'static str> {")
lines.append("    TPCDS_QUERIES.iter().map(|query| query.id)")
lines.append("}")
lines.append("")

with open(OUT_FILE, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print(f"[extract_tpcds_queries] wrote {OUT_FILE} ({len(queries)} queries)")
PY
