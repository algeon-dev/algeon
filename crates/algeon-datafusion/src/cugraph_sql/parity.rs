/// Comparator family expected for a parity row.
///
/// Comparator family used by the registry-driven parity harness.
#[doc(hidden)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ParityComparator {
    /// Exact equality on integer columns after sort-by-vertex.
    ExactInt,
    /// Per-vertex absolute and relative tolerance on floating-point
    /// columns after sort-by-vertex.
    Numeric,
    /// Compare partitions as set-of-sets, ignoring label renaming.
    PartitionEquivalence,
    /// Validate a randomized partition by vertex coverage, a bounded
    /// community count, and modularity relative to the oracle baseline.
    ///
    /// Unlike [`Self::PartitionEquivalence`], this intentionally does not
    /// require a byte-identical partition across cuGraph builds or across
    /// same-seed replays on the same build.
    PartitionQuality,
    /// Seeded random output; sequence + grouping must match plus the
    /// distribution baseline.
    SeededSequence,
    /// Approximate ranking results compared by Spearman correlation.
    RankCorrelation,
    /// Edge sets canonicalized as unordered `(min, max)` pairs.
    EdgeSubgraph,
    /// Strict equality on the top-K vertex set when the result is sorted
    /// by descending score. Used with cuGraph-curated reference CSVs
    /// copied under `fixture/graph/cugraph/ref/katz/*.csv` by the local
    /// fixture preparer. Their canonical top-K vertex ordering matches
    /// the upstream cuGraph Python test
    /// (`topKVertices(katz, "katz_centrality", k)`).
    TopKVertices,
    /// Compare `(first, second, similarity)` rows as a multiset.
    ///
    /// Similarity is defined over an explicit input relation: duplicate,
    /// reversed, and self pairs are all semantically observable, so the
    /// normal vertex-order comparators are not valid here.
    SimilarityMultiset,
}

impl ParityComparator {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ExactInt => "exact_int",
            Self::Numeric => "numeric",
            Self::PartitionEquivalence => "partition_equivalence",
            Self::PartitionQuality => "partition_quality",
            Self::SeededSequence => "seeded_sequence",
            Self::RankCorrelation => "rank_correlation",
            Self::EdgeSubgraph => "edge_subgraph",
            Self::TopKVertices => "top_k_vertices",
            Self::SimilarityMultiset => "similarity_multiset",
        }
    }
}

/// Source of ground truth for a parity row.
#[doc(hidden)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ParityTruthSource {
    /// Local oracle JSON generated by `fixture/graph/cugraph_oracle.py`.
    OracleJson,
    /// cuGraph reference CSV copied under `fixture/graph/cugraph/ref/`.
    /// The path is expressed relative to the data root.
    RefCsv { path: &'static str },
    /// A small, hand-derived result document for a contract that is simpler
    /// to audit directly than to delegate to the Python oracle.
    ///
    /// The document contains a `result` object with the same column-array
    /// shape as oracle JSON. It deliberately has no generated-oracle path.
    HandVerified { document_json: &'static str },
}

impl ParityTruthSource {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::OracleJson => "oracle_json",
            Self::RefCsv { .. } => "ref_csv",
            Self::HandVerified { .. } => "hand_verified",
        }
    }
}

/// Per-row tolerance for floating-point comparators.
///
/// Integer comparators ignore both fields. `PartitionQuality` uses them as
/// absolute and relative modularity tolerances.
#[doc(hidden)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ParityTolerance {
    pub abs: f64,
    pub rel: f64,
}

impl ParityTolerance {
    pub const fn exact() -> Self {
        Self { abs: 0.0, rel: 0.0 }
    }
}

/// One row in the cuGraph parity spec registry.
///
/// Adding an algorithm/dataset combination is one new const entry in
/// [`CUGRAPH_PARITY_SPECS`], not a new file. `params_json` is the
/// canonical JSON form of the algorithm parameters; it must match
/// exactly the `header.params` of the generated oracle JSON.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct ParitySpec {
    /// Stable label used in test output and in plan-display strings.
    pub label: &'static str,
    pub algorithm: CugraphAlgorithm,
    /// Dataset id from local `fixture/graph/cugraph/manifest.json`.
    pub dataset: &'static str,
    /// Canonical JSON parameter object. Empty `{}` is allowed.
    pub params_json: &'static str,
    /// RNG seed; recorded in the oracle JSON header and pinned by the
    /// `SeededSequence` comparator family.
    pub seed: Option<u64>,
    pub truth_source: ParityTruthSource,
    /// Oracle JSON path relative to `fixture/graph/cugraph/oracle/` for
    /// generated-oracle and reference-CSV rows. Hand-verified rows have no
    /// generated oracle, so this is absent.
    pub oracle_relpath: Option<&'static str>,
    pub comparator: ParityComparator,
    pub tolerance: ParityTolerance,
}

