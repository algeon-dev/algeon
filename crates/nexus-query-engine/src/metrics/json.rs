fn policy_count<T: PartialEq>(actual: T, expected: T) -> u64 {
    u64::from(actual == expected)
}

fn optional_query_id(value: Option<&QueryId>) -> Option<&str> {
    value.map(QueryId::as_str)
}

fn optional_plan_node_id(value: Option<&PlanNodeId>) -> Option<&str> {
    value.map(PlanNodeId::as_str)
}

fn optional_compiled_task_id(value: Option<&CompiledTaskId>) -> Option<&str> {
    value.map(CompiledTaskId::as_str)
}

fn optional_u64_json(value: Option<u64>) -> Value {
    value.map_or(Value::Null, |value| json!(value))
}

fn duration_ns(value: std::time::Duration) -> u64 {
    value.as_nanos().min(u128::from(u64::MAX)) as u64
}

fn i128_json(value: i128) -> Value {
    i64::try_from(value).map_or_else(|_| json!(value.to_string()), |value| json!(value))
}

fn facts_json(facts: &BTreeMap<String, String>) -> Value {
    json!(facts)
}
